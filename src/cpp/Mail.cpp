void Mail::init(int n, const uint8_t* fromData, const uint8_t* subjData) {
    mail_id = n;
    face    = fromData[0];
    from    = fromData[1];
    to      = fromData[2];
    subject = fromData[3];
    if (from < 8) str_f = str_name[from];
    if (to   < 5) str_t = net_name[to];
    int len = 0;
    while (len < 30 && subjData[len] != 0) ++len;
    str_s.assign(reinterpret_cast<const char*>(subjData), len);
}
